export type FunctionalTemplate = keyof typeof englishTemplates;
type PlaceholderNames<Value extends string> =
  Value extends `${string}{${infer Name}}${infer Rest}`
    ? Name | PlaceholderNames<Rest>
    : never;
type TemplateValues<Key extends FunctionalTemplate> = Record<
  PlaceholderNames<Key>,
  string | number
>;

export function translate(locale: Locale, message: FunctionalMessage) {
  return locale === "en" ? english[message] : message;
}

export function translateKnown(locale: Locale, message: string) {
  if (locale !== "en") return message;
  if (Object.prototype.hasOwnProperty.call(english, message)) {
    return english[message as FunctionalMessage];
  }
  const existingTrack = /^Ya existe en tu biblioteca: “(.+)”\.$/.exec(message);
  if (existingTrack) return `Already in your library: “${existingTrack[1]}”.`;
  const crateConflict =
    /^El crate “(.+)” ya existe en otra jerarquía\. Renómbralo antes de reconciliar\.$/.exec(
      message,
    );
  if (crateConflict) {
    return `Crate “${crateConflict[1]}” already exists in another hierarchy. Rename it before reconciling.`;
  }
  const crateUpdated =
    /^Crate actualizado con (\d+) pistas en el orden de VirtualDJ\.$/.exec(
      message,
    );
  if (crateUpdated) {
    return `Crate updated with ${crateUpdated[1]} tracks in VirtualDJ order.`;
  }
  const crateMerged =
    /^Crate combinado con (\d+) pistas vinculadas de VirtualDJ\.$/.exec(message);
  if (crateMerged) {
    return `Crate merged with ${crateMerged[1]} linked VirtualDJ tracks.`;
  }
  const restored = /^Copia restaurada: (\d+) pistas y (\d+) crates\.$/.exec(
    message,
  );
  if (restored) {
    return `Backup restored: ${restored[1]} tracks and ${restored[2]} crates.`;
  }
  return message;
}

export function formatMessage<Key extends FunctionalTemplate>(
  locale: Locale,
  template: Key,
  values: TemplateValues<Key>,
) {
  const localized = locale === "en" ? englishTemplates[template] : template;
  return localized.replace(/\{([^}]+)\}/g, (match, name: string) => {
    const value = values[name as keyof typeof values];
    return value === undefined ? match : String(value);
  });
}

